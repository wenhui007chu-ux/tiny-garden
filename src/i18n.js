const KEY = 'farm-lang';
// 加个环境守卫：config.js 现在会 import 本模块，脱离浏览器跑脚本时不至于直接炸
const store = typeof localStorage !== 'undefined' ? localStorage : null;
export let lang = (() => {
  const saved = store?.getItem(KEY);
  return LANGS.some(l => l.id === saved) ? saved : 'zh';
})();

// 查不到就退回中文，再查不到就把 key 原样吐出来——宁可露个键名，也别显示 undefined
export const t = (key) => DICT[lang]?.[key] ?? DICT.zh[key] ?? key;

// 给「配置表里的名字」用：查不到就回落到 config 里的原文（中文），
// 这样新加作物/道具忘了配翻译时，顶多显示中文，不会变成 seed.xxx 这种键名。
export const tf = (key, fallback) => DICT[lang]?.[key] ?? fallback ?? DICT.zh[key] ?? key;

// 带变量替换：tp('plant.locked', { cost: 1000 }) → 文案里的 {cost} 会被替换掉
export const tp = (key, vars = {}) =>
  Object.entries(vars).reduce((s, [k, v]) => s.split(`{${k}}`).join(v), t(key));

// 拼名字用的分隔符：中文「黄金番茄」不留空格，英俄「Gold Tomato」得留
export const nameSep = () => (lang === 'zh' ? '' : ' ');

export function setLang(id) {
  if (!LANGS.some(l => l.id === id) || id === lang) return false;
  store?.setItem(KEY, id);
  return true;
}

// 把静态 HTML 里标了 data-i18n / data-i18n-title 的地方填上当前语言
export function applyStaticI18n() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const v = t(el.dataset.i18n);
    if (el.dataset.i18nHtml !== undefined) el.innerHTML = v;
    else el.textContent = v;
  });
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    el.title = t(el.dataset.i18nTitle);
  });
  document.documentElement.lang = lang === 'zh' ? 'zh-CN' : lang;
}
